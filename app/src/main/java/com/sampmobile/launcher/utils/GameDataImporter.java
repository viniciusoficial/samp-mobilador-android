package com.sampmobile.launcher.utils;

import android.content.ContentResolver;
import android.content.Context;
import android.database.Cursor;
import android.net.Uri;
import android.provider.OpenableColumns;

import java.io.BufferedInputStream;
import java.io.File;
import java.io.FileOutputStream;
import java.io.FilterInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.concurrent.atomic.AtomicBoolean;
import java.util.zip.ZipEntry;
import java.util.zip.ZipInputStream;

/**
 * Streams a game-data .zip archive (generated by tools/gamedata/build_gamedata.py or any
 * standard GTA:SA + SA-MP mobile package) directly into the app's own
 * external files/ directory.
 *
 * Writing from the launcher's own UID avoids Android 11-15 scoped-storage and
 * third-party file-manager EACCES permission failures, and automatically strips
 * accidental outer wrapper folders (e.g. files/ or gamedata/files/).
 */
public final class GameDataImporter {

    private static final int IO_BUFFER_SIZE = 64 * 1024;

    private static final Set<String> GAME_ROOT_DIRS = new HashSet<>(Arrays.asList(
            "samp", "anim", "audio", "data", "models", "texdb"
    ));

    private static final Set<String> GAME_ROOT_FILES = new HashSet<>(Arrays.asList(
            "stream.ini"
    ));

    private static final String[] REQUIRED_CORE_FILES = {
            "texdb/gta3.img",
            "texdb/samp.img",
            "texdb/samp/samp.txt",
            "SAMP/main.scm",
            "models/coll/peds.col"
    };

    private GameDataImporter() {}

    public interface ProgressListener {
        void onProgress(int percent, int extractedFiles, String currentPath);
    }

    public static final class ImportResult {
        public final int extractedFiles;
        public final long extractedBytes;
        public final boolean ready;
        public final boolean cancelled;
        public final List<String> missingCoreFiles;

        public ImportResult(int extractedFiles, long extractedBytes, boolean ready,
                            boolean cancelled, List<String> missingCoreFiles) {
            this.extractedFiles = extractedFiles;
            this.extractedBytes = extractedBytes;
            this.ready = ready;
            this.cancelled = cancelled;
            this.missingCoreFiles = missingCoreFiles;
        }
    }

    /**
     * Returns a list of missing core files under filesDir (empty list means ready).
     */
    public static List<String> findMissingCoreFiles(File filesDir) {
        List<String> missing = new ArrayList<>();
        if (filesDir == null || !filesDir.isDirectory()) {
            missing.addAll(Arrays.asList(REQUIRED_CORE_FILES));
            return missing;
        }
        for (String rel : REQUIRED_CORE_FILES) {
            File f = new File(filesDir, rel);
            if (!f.isFile() || f.length() <= 0) {
                missing.add(rel);
            }
        }
        return missing;
    }

    public static boolean isGameDataReady(File filesDir) {
        return findMissingCoreFiles(filesDir).isEmpty();
    }

    /**
     * Normalizes a ZIP entry path to a relative path anchored at a known GTA:SA / SA-MP
     * root directory or file (SAMP/, anim/, audio/, data/, models/, texdb/, stream.ini).
     *
     * Handles both flat archives ("SAMP/main.scm") and wrapped archives
     * ("files/SAMP/main.scm", "gamedata/files/texdb/samp.img").
     * Returns null if the entry should be skipped or fails safety checks.
     */
    public static String normalizeZipEntryPath(String rawName) {
        if (rawName == null || rawName.isEmpty()) {
            return null;
        }
        String unified = rawName.replace('\\', '/');
        while (unified.startsWith("/")) {
            unified = unified.substring(1);
        }
        if (unified.isEmpty() || unified.endsWith("/")) {
            return null;
        }

        String[] rawParts = unified.split("/");
        List<String> parts = new ArrayList<>(rawParts.length);
        for (String seg : rawParts) {
            if (seg.isEmpty() || ".".equals(seg)) {
                continue;
            }
            if ("..".equals(seg)) {
                return null; // Reject path traversal
            }
            if ("__MACOSX".equalsIgnoreCase(seg) || ".DS_Store".equalsIgnoreCase(seg)) {
                return null;
            }
            parts.add(seg);
        }
        if (parts.isEmpty()) {
            return null;
        }

        int anchor = -1;
        for (int i = 0; i < parts.size(); i++) {
            String low = parts.get(i).toLowerCase(Locale.US);
            if (GAME_ROOT_DIRS.contains(low) && i < parts.size() - 1) {
                anchor = i;
                break;
            }
            if (GAME_ROOT_FILES.contains(low) && i == parts.size() - 1) {
                anchor = i;
                break;
            }
        }
        if (anchor < 0) {
            return null;
        }

        StringBuilder sb = new StringBuilder();
        for (int i = anchor; i < parts.size(); i++) {
            if (i > anchor) {
                sb.append('/');
            }
            sb.append(parts.get(i));
        }
        return sb.toString();
    }

    /**
     * Existing user configuration and server lists should never be clobbered by a data pack.
     */
    public static boolean shouldPreserveExisting(String normalizedRelPath) {
        if (normalizedRelPath == null) {
            return false;
        }
        String low = normalizedRelPath.toLowerCase(Locale.US);
        return "samp/settings.json".equals(low)
                || "servers.json".equals(low)
                || "recent.json".equals(low)
                || low.startsWith("logcat/");
    }

    /**
     * Queries total byte length of a SAF document Uri, or -1 if unknown.
     */
    public static long queryDocumentSize(Context context, Uri uri) {
        if (context == null || uri == null) {
            return -1L;
        }
        ContentResolver cr = context.getContentResolver();
        try (Cursor c = cr.query(uri, new String[]{OpenableColumns.SIZE}, null, null, null)) {
            if (c != null && c.moveToFirst()) {
                int idx = c.getColumnIndex(OpenableColumns.SIZE);
                if (idx >= 0 && !c.isNull(idx)) {
                    return c.getLong(idx);
                }
            }
        } catch (Exception ignored) {
        }
        return -1L;
    }

    /**
     * Imports a game-data .zip from an Android Storage Access Framework Uri into filesDir.
     */
    public static ImportResult importFromUri(Context context, Uri zipUri, File filesDir,
                                             ProgressListener listener, AtomicBoolean cancelled) throws IOException {
        long totalBytes = queryDocumentSize(context, zipUri);
        try (InputStream raw = context.getContentResolver().openInputStream(zipUri)) {
            if (raw == null) {
                throw new IOException(I18n.tr("无法打开所选 ZIP 文件"));
            }
            return importFromStream(raw, totalBytes, filesDir, listener, cancelled);
        }
    }

    /**
     * Streams and extracts a game-data ZIP InputStream into filesDir.
     */
    public static ImportResult importFromStream(InputStream rawIn, long totalZipBytes, File filesDir,
                                                ProgressListener listener, AtomicBoolean cancelled) throws IOException {
        if (filesDir == null) {
            throw new IOException(I18n.tr("目标 files 目录不可用"));
        }
        if (!filesDir.exists() && !filesDir.mkdirs()) {
            throw new IOException(I18n.tr("无法创建目录: ") + filesDir.getAbsolutePath());
        }
        String canonicalRoot = filesDir.getCanonicalPath();
        if (!canonicalRoot.endsWith(File.separator)) {
            canonicalRoot = canonicalRoot + File.separator;
        }

        CountingInputStream counter = new CountingInputStream(new BufferedInputStream(rawIn, IO_BUFFER_SIZE));
        byte[] buf = new byte[IO_BUFFER_SIZE];
        int extractedFiles = 0;
        long extractedBytes = 0L;
        int lastReportedPct = -1;
        long lastNotifyMs = 0L;
        boolean wasCancelled = false;

        try (ZipInputStream zis = new ZipInputStream(counter)) {
            ZipEntry entry;
            while ((entry = zis.getNextEntry()) != null) {
                if (cancelled != null && cancelled.get()) {
                    wasCancelled = true;
                    break;
                }
                if (entry.isDirectory()) {
                    zis.closeEntry();
                    continue;
                }

                String rel = normalizeZipEntryPath(entry.getName());
                if (rel == null) {
                    zis.closeEntry();
                    continue;
                }

                File outFile = new File(filesDir, rel);
                String canonicalOut = outFile.getCanonicalPath();
                if (!canonicalOut.startsWith(canonicalRoot)) {
                    throw new IOException(I18n.tr("检测到非法 ZIP 路径: ") + entry.getName());
                }

                if (shouldPreserveExisting(rel) && outFile.isFile() && outFile.length() > 0) {
                    zis.closeEntry();
                    continue;
                }

                File parent = outFile.getParentFile();
                if (parent != null && !parent.exists() && !parent.mkdirs()) {
                    throw new IOException(I18n.tr("无法创建子目录: ") + parent.getAbsolutePath());
                }

                try (FileOutputStream fos = new FileOutputStream(outFile)) {
                    int n;
                    while ((n = zis.read(buf)) > 0) {
                        if (cancelled != null && cancelled.get()) {
                            wasCancelled = true;
                            break;
                        }
                        fos.write(buf, 0, n);
                        extractedBytes += n;

                        if (listener != null) {
                            long now = System.currentTimeMillis();
                            int pct = computePercent(counter.bytesRead, totalZipBytes);
                            if (pct != lastReportedPct || (now - lastNotifyMs) >= 180L) {
                                lastReportedPct = pct;
                                lastNotifyMs = now;
                                listener.onProgress(pct, extractedFiles, rel);
                            }
                        }
                    }
                }
                if (wasCancelled) {
                    // Clean up partial file on cancel
                    //noinspection ResultOfMethodCallIgnored
                    outFile.delete();
                    break;
                }
                extractedFiles++;
                zis.closeEntry();

                if (listener != null) {
                    int pct = computePercent(counter.bytesRead, totalZipBytes);
                    lastReportedPct = pct;
                    lastNotifyMs = System.currentTimeMillis();
                    listener.onProgress(pct, extractedFiles, rel);
                }
            }
        }

        List<String> missing = findMissingCoreFiles(filesDir);
        boolean ready = !wasCancelled && missing.isEmpty();
        if (listener != null && !wasCancelled) {
            listener.onProgress(100, extractedFiles, "");
        }
        return new ImportResult(extractedFiles, extractedBytes, ready, wasCancelled, missing);
    }

    private static int computePercent(long read, long total) {
        if (total <= 0L) {
            return -1;
        }
        int pct = (int) Math.min(99L, (read * 100L) / total);
        return Math.max(0, pct);
    }

    private static final class CountingInputStream extends FilterInputStream {
        long bytesRead = 0L;

        CountingInputStream(InputStream in) {
            super(in);
        }

        @Override
        public int read() throws IOException {
            int b = super.read();
            if (b >= 0) {
                bytesRead++;
            }
            return b;
        }

        @Override
        public int read(byte[] b, int off, int len) throws IOException {
            int n = super.read(b, off, len);
            if (n > 0) {
                bytesRead += n;
            }
            return n;
        }
    }
}
